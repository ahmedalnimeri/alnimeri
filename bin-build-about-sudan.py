#!/usr/bin/env python3
"""Render About's Sixteen Days of Sudan: twelve small frames from Ahmed's
personal AI image series on Instagram (@by_nimeri), between On Set and the
comments. Ahmed chose the twelve and their order (11 Oct 2026) and asked for
a small section, not a big one: a short heading, one line, a link to the
series, and the frames as small squares (six to a row on a wide screen, four
on a phone). No lightbox, no motion of its own. The line says what they are
(made with Midjourney and ChatGPT, posted labelled as AI), and so does every
alt, so they never read as photographs beside On Set's.

  python3 bin-build-about-sudan.py encode RAW_DIR   # RAW_DIR/<code>.jpg -> assets/sudan/
  python3 bin-build-about-sudan.py                  # render about.html

Each frame is assets/sudan/<code>-320|640-<md5[:8]>.jpg|.webp (square, JPEG
q86 progressive, WebP q82, metadata stripped, as the Frames' stills): a
changed frame takes a new name and the old one is deleted. The build refuses
a frame with two files, a name that is not its bytes' md5, or a file no frame
names. Run bin-stamp-assets.py afterwards.
"""
import glob, hashlib, html, os, re, subprocess, sys, tempfile

PAGE, DIR = 'about.html', 'assets/sudan'
WIDTHS = (320, 640)
START = '<!-- SUDAN:START (generated by bin-build-about-sudan.py) -->'
END = '<!-- SUDAN:END -->'
INSTAGRAM = 'https://www.instagram.com/by_nimeri/'
esc = lambda s: html.escape(s, quote=True)

# (post-frame code, the day's label, what the frame shows) in Ahmed's order.
FRAMES = [
    ('d01-05', 'Day 1 · The Jirtig', 'Hennaed hands with jewellery'),
    ('d02-01', 'Day 2 · The Women', 'A woman in a toub moving by the river'),
    ('d03-07', 'Day 3 · The Nile', 'A boat in morning mist'),
    ('d04-02', 'Day 4 · Home', 'A hand reaching into a shared tray of dishes'),
    ('d05-03', 'Day 5 · The Neighbourhood', 'Football in the dust at dusk'),
    ('d05-07', 'Day 5 · The Neighbourhood', 'A man pushing an ice-cream cart'),
    ('d06-01', 'Day 6 · Sudan in Motion', 'A traffic officer against red cars'),
    ('d06-09', 'Day 6 · Sudan in Motion', 'A boy running with bread, dogs following'),
    ('d07-03', 'Day 7 · The Farewell', 'A passport on a folded jalabiya'),
    ('d07-17', 'Day 7 · The Farewell', 'A departure stamp, مغادرة 03 JUN 2019'),
    ('d08-01', 'Day 8 · The Uni', 'The University of Khartoum clock tower'),
    ('d09-01', 'Day 9 · Sayed Khalifa, «إزيكم كيفنكم»', 'An embrace in white jalabiyas'),
]

LINE = ('A personal series on Instagram, one part of Sudan each day. '
        'Made with Midjourney and ChatGPT and posted labelled as AI.')
# six to a row up to 168px each on a wide screen, four across a phone
SIZES = '(max-width: 700px) calc(25vw - 12px), 168px'

def md5(path):
    return hashlib.md5(open(path, 'rb').read()).hexdigest()[:8]

def encode(raw):
    os.makedirs(DIR, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for code, _, _ in FRAMES:
            src = os.path.join(raw, f'{code}.jpg')
            if not os.path.exists(src): sys.exit(f'missing {src}')
            for w in WIDTHS:
                fit = ['magick', src, '-auto-orient', '-colorspace', 'sRGB', '-resize', f'{w}x{w}^',
                       '-gravity', 'center', '-extent', f'{w}x{w}', '-strip']
                jpg, png = os.path.join(tmp, 'f.jpg'), os.path.join(tmp, 'f.png')
                subprocess.run(fit + ['-interlace', 'JPEG', '-quality', '86', jpg], check=True)
                subprocess.run(fit + [png], check=True)
                webp = os.path.join(tmp, 'f.webp')
                subprocess.run(['cwebp', '-quiet', '-q', '82', '-m', '6', '-metadata', 'none', png, '-o', webp], check=True)
                for made, ext in ((jpg, 'jpg'), (webp, 'webp')):
                    name = f'{DIR}/{code}-{w}-{md5(made)}.{ext}'
                    for old in glob.glob(f'{DIR}/{code}-{w}-*.{ext}'):
                        if old != name: os.remove(old); print('removed', old)
                    if not os.path.exists(name):
                        os.replace(made, name); print('wrote', name)

def files(code):
    """One frame's four files, checked: one of each, each named by its bytes."""
    out = {}
    for w in WIDTHS:
        for ext in ('jpg', 'webp'):
            hits = sorted(glob.glob(f'{DIR}/{code}-{w}-*.{ext}'))
            if len(hits) != 1:
                sys.exit(f'{DIR}/: frame {code} needs one {w}px .{ext}, has {len(hits)}')
            m = re.fullmatch(rf'{re.escape(code)}-{w}-([0-9a-f]{{8}})\.{ext}', os.path.basename(hits[0]))
            if not m or m.group(1) != md5(hits[0]):
                sys.exit(f'{hits[0]}: not named by the md5[:8] of its bytes (a changed frame takes a new name)')
            out[(w, ext)] = '/' + hits[0]
    return out

def render():
    codes = [c for c, _, _ in FRAMES]
    stray = sorted(p for p in glob.glob(f'{DIR}/*') if os.path.basename(p)[:6] not in codes)
    if stray: sys.exit(f'{DIR}/: {", ".join(stray)} is in no frame (delete a replaced frame)')
    items = []
    for code, label, what in FRAMES:
        fl = files(code)
        webp = ', '.join(f'{fl[(w, "webp")]} {w}w' for w in WIDTHS)
        jpg = ', '.join(f'{fl[(w, "jpg")]} {w}w' for w in WIDTHS)
        items.append(
            f'      <li class="sudan__fr"><picture><source type="image/webp" srcset="{webp}" sizes="{SIZES}">'
            f'<img src="{fl[(320, "jpg")]}" srcset="{jpg}" sizes="{SIZES}" '
            f'alt="{esc(what + " (AI-generated)")}" title="{esc(label)}" width="640" height="640" '
            f'loading="lazy" decoding="async"></picture></li>')
    return f'''{START}
  <section class="sudan" id="sudan" aria-labelledby="sudan-title">
    <div class="sudan__head">
      <h2 class="sudan__title" id="sudan-title">Sixteen Days of Sudan</h2>
      <p class="sudan__sub">{esc(LINE)}
        <a href="{INSTAGRAM}" target="_blank" rel="noopener">The series on Instagram <span aria-hidden="true">&#8599;</span></a></p>
    </div>
    <ul class="sudan__grid">
{chr(10).join(items)}
    </ul>
  </section>
  {END}
'''

def build():
    page = open(PAGE).read()
    block = render()
    if START in page:
        out = re.sub(re.escape(START) + r'[\s\S]*?' + re.escape(END) + r'\n?', lambda m: block, page, count=1)
    else:
        # after On Set, before the comments
        s = page.index('<section class="section" id="onset">')
        e = page.index('</section>', s) + len('</section>\n')
        out = page[:e] + '\n' + block + page[e:]
    # assert the RESULT, not the precondition
    a, b = out.index(START), out.index(END)
    assert out.count(START) == 1 and out.count(END) == 1
    assert out.index('id="onset"') < a < b < out.index('id="said"')
    assert out[a:b].count('<li class="sudan__fr">') == len(FRAMES)
    if out != page: open(PAGE, 'w').write(out)
    print(f'{PAGE}: Sixteen Days of Sudan — {len(FRAMES)} frames' + ('' if out != page else ' (unchanged)'))

if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'build'
    if cmd == 'encode': encode(sys.argv[2])
    else: build()
